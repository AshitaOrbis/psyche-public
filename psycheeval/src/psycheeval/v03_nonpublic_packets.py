"""v0.3 PI-matched nonpublic source packets.

Per Phase -1.9 decision (option (a) approved 2026-05-19): C5_NONPUBLIC is
authored as PI-matched fictional biographical narratives. Each packet matches
the trait pattern of the corresponding C5 (public-anchor) packet while
removing all references to specific public roles, organizations, or events.

The C5 vs C5_NONPUBLIC contrast then isolates the public-anchor narrative-form
effect from the source-packet form effect, holding the trait pattern roughly
constant across the contrast.

Construction principle: each packet is structurally parallel to the C5 packet
(same 4-5 sections, similar length, similar number of bullets) but the
content is generic enough that no specific public figure could be identified
from it. Fictional biographical color is added where useful for behavioral
inference, but it must be invented context not real biography.

Author note: these packets are matched at the *behavioral trait* level, not
at the *identity* level. The matched persona is "a person who behaves like
the public anchor would" stripped of the cues that would reveal the anchor.

NOTE: These packets share length-target (~3,365-4,392 chars) with the
corresponding C5 packets in v0.2.
"""

